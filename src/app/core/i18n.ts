@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly lang = signal<Lang>(readInitial());

  constructor() {
    effect(() => {
      const lang = this.lang();
      document.documentElement.setAttribute('lang', lang);
      localStorage.setItem(STORAGE_KEY, lang);
    });
  }

  set(lang: Lang): void {
    this.lang.set(lang);
  }

  /**
   * Look up a key for the current language (falling back to English, then the key
   * itself). Optional params replace `{token}` placeholders in the string.
   */
  translate(key: string, params?: Record<string, string | number>): string {
    const lang = this.lang();
    let value = DICTIONARY[lang][key] ?? DICTIONARY.en[key] ?? key;
    if (params) {
      for (const [name, val] of Object.entries(params)) {
        value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), String(val));
      }
    }
    return value;
  }
}

function readInitial(): Lang {
  const stored = localStorage.getItem(STORAGE_KEY);
  return stored === 'hy' || stored === 'ru' || stored === 'ko' ? stored : 'en';
}
